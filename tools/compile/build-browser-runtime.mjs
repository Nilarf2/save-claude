// Keep the GitHub source preview runnable without inline scripts/import maps.
import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const upstream = JSON.parse(await readFile(resolve(root, 'engine/UPSTREAM.json'), 'utf8'));
const output = resolve(root, 'web/engine-runtime.js');
const result = await build({
  stdin: {
    contents: "export { compileStory } from '@text-adventure/content';\nexport { createSession } from '@text-adventure/core';\n",
    resolveDir: root,
    sourcefile: 'browser-engine-entry.js',
    loader: 'js',
  },
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: false,
  legalComments: 'eof',
  write: false,
  banner: { js: `// Generated by tools/compile/build-browser-runtime.mjs from engine ${upstream.commit}.` },
});
const bytes = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  const existing = await readFile(output);
  if (!existing.equals(Buffer.from(bytes))) throw new Error('Browser engine snapshot is stale; run npm run build');
  console.log('PASS: browser engine bundle matches the vendored source.');
} else {
  await writeFile(output, bytes);
  console.log(`Built browser engine: ${bytes.length} bytes; no inline import map required.`);
}
